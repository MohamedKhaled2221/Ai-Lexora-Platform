from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, Iterable, List
from uuid import uuid4

from docx import Document

from .errors import AssemblyError, ValidationError
from .guided_input import validate_field_types, validate_guided_input
from .placeholder_validator import (
    validate_approved_clause_set,
    validate_clause_placement,
    validate_no_unresolved_placeholders,
    validate_prohibited_clauses,
    validate_required_clauses,
    validate_source_traceability,
)
from .schemas import (
    AssembledDraft,
    AssembledSection,
    ClauseDecision,
    DraftStatus,
    GuidedDocumentRequest,
    TemplateDefinition,
)
from src.schemas.m5_contract import (
    ApprovedClause,
    TemplateClauseRequirement,
)

class DocumentAssembler:
    """
    Deterministic controlled document assembly.

    Legal text is never generated by this component.
    Only approved clauses supplied to the assembler are inserted.
    """

    def assemble(
        self,
        request: GuidedDocumentRequest,
        template: TemplateDefinition,
        requirement: TemplateClauseRequirement,
        clauses: Iterable[ApprovedClause],
        decisions: Iterable[ClauseDecision] = (),
    ) -> AssembledDraft:

        # ---------------------------------------------------------
        # 1. Validate guided user input
        # ---------------------------------------------------------
        validate_guided_input(request, template)
        validate_field_types(request, template)
        clauses = self._sort_clauses(
            list(clauses),
            requirement,
        )

        decisions = list(decisions)

        # ---------------------------------------------------------
        # 2. Validate approved clauses
        # ---------------------------------------------------------
        validate_approved_clause_set(
            clauses,
            request.document_type,
            request.jurisdiction,
        )

        validate_prohibited_clauses(
            clauses,
            requirement,
        )

        # ---------------------------------------------------------
        # 3. Validate required clauses
        #
        # Template requirements are the source of truth.
        # Decisions may additionally describe why a clause is
        # required, optional, prohibited, etc.
        # ---------------------------------------------------------
        validate_required_clauses(
            clauses,
            requirement.required_clauses,
        )

        # ---------------------------------------------------------
        # 3.1 Validate clause placement
        #
        # Every approved clause must have an insertion_key
        # that exists in the template's section_placeholders.
        # ---------------------------------------------------------
        validate_clause_placement(
            clauses,
            requirement,
        )

        # ---------------------------------------------------------
        # 4. Handle lawyer-input conditions
        # ---------------------------------------------------------
        unresolved = [
            decision
            for decision in decisions
            if decision.decision == "requires_lawyer_input"
        ]

        if unresolved:
            raise ValidationError(
                "Assembly cannot continue because lawyer input is required: "
                + "; ".join(
                    decision.reason or decision.clause_id
                    for decision in unresolved
                )
            )

        # ---------------------------------------------------------
        # 5. Validate template file
        # ---------------------------------------------------------
        if not template.file_path:
            raise AssemblyError(
                f"Template {template.template_id} has no file_path"
            )

        template_path = Path(template.file_path)

        if not template_path.exists():
            raise AssemblyError(
                f"Template file does not exist: {template.file_path}"
            )

        # ---------------------------------------------------------
        # 6. Load DOCX template
        # ---------------------------------------------------------
        try:
            doc = Document(str(template_path))
        except Exception as exc:
            raise AssemblyError(
                f"Failed to load DOCX template: {template.file_path}"
            ) from exc

        sections: List[AssembledSection] = []
        order = 0

        # ---------------------------------------------------------
        # 7. Replace normal user-input placeholders
        # ---------------------------------------------------------
        order = self._process_paragraphs(
            doc.paragraphs,
            request.fields,
            template.template_id,
            sections,
            order,
        )

        # ---------------------------------------------------------
        # 8. Replace placeholders inside tables
        # ---------------------------------------------------------
        for table in doc.tables:
            for row in table.rows:
                for cell in row.cells:
                    order = self._process_paragraphs(
                        cell.paragraphs,
                        request.fields,
                        template.template_id,
                        sections,
                        order,
                    )

        # ---------------------------------------------------------
        # 9. Insert approved clauses
        #
        # IMPORTANT:
        # insertion_key must come from the approved contract.
        # We do not invent placement keys.
        # ---------------------------------------------------------
        used_markers = self._replace_clause_markers(
            doc,
            clauses,
            requirement,
            sections,
        )

        self._clear_unused_clause_markers(
            doc,
            requirement,
            used_markers,
        )

        # ---------------------------------------------------------
        # 10. Read final document text
        # ---------------------------------------------------------
        plain_text = self._extract_document_text(doc)

        # ---------------------------------------------------------
        # 11. Final placeholder validation
        # ---------------------------------------------------------
        validate_no_unresolved_placeholders(
            plain_text,
            template,
        )

        # ---------------------------------------------------------
        # 12. Build assembled draft
        # ---------------------------------------------------------
        draft = AssembledDraft(
            draft_id=str(uuid4()),
            request_id=request.request_id,
            template_id=template.template_id,
            template_version=template.version,
            document_type=template.document_type,
            jurisdiction=template.jurisdiction,
            sections=sections,
            plain_text=plain_text,
            status=DraftStatus.DRAFT,
        )

        # ---------------------------------------------------------
        # 13. Final provenance validation
        # ---------------------------------------------------------
        validate_source_traceability(draft)

        return draft

    # =================================================================
    # FIELD PROCESSING
    # =================================================================

    @staticmethod
    def _process_paragraphs(
        paragraphs,
        fields: Dict[str, object],
        template_id: str,
        sections: List[AssembledSection],
        order: int,
    ) -> int:

        for paragraph in paragraphs:
            original = paragraph.text

            if not original.strip():
                continue

            replaced = DocumentAssembler._replace_fields(
                original,
                fields,
            )

            if replaced != original:
                DocumentAssembler._replace_paragraph_text(
                    paragraph,
                    replaced,
                )

            order += 1

            sections.append(
                AssembledSection(
                    section_id=f"sec-{order}",
                    text=replaced,
                    order=order,
                    source_type="template",
                    source_id=template_id,
                )
            )

        return order

    @staticmethod
    def _replace_fields(
        text: str,
        fields: Dict[str, object],
    ) -> str:
        """
        Replace normal user-input placeholders.

        Example:
            {{employee_name}}
            {{company_name}}

        Clause markers are deliberately left untouched and are
        processed separately.
        """

        def replace(match: re.Match[str]) -> str:
            key = match.group(1)

            if key.startswith("CLAUSE:"):
                return match.group(0)

            if key not in fields:
                return match.group(0)

            value = fields[key]

            if value is None:
                return ""

            return str(value)

        return re.sub(
            r"\{\{([A-Za-z0-9_.:-]+)\}\}",
            replace,
            text,
        )
    @staticmethod
    def _clear_unused_clause_markers(
        doc: Document,
        requirement: TemplateClauseRequirement,
        used_markers: set[str],
    ) -> None:

        unused_markers = {
            marker
            for marker
            in requirement.section_placeholders.values()
            if marker not in used_markers
        }

        if not unused_markers:
            return

        paragraphs = list(doc.paragraphs)

        for table in doc.tables:
            for row in table.rows:
                for cell in row.cells:
                    paragraphs.extend(
                        cell.paragraphs
                    )

        for paragraph in paragraphs:

            text = paragraph.text
            updated = text

            for marker in unused_markers:
                updated = updated.replace(
                    marker,
                    "",
                )

            if updated != text:
                DocumentAssembler._replace_paragraph_text(
                    paragraph,
                    updated,
                )
    @staticmethod
    def _replace_paragraph_text(
        paragraph,
        text: str,
    ) -> None:
        """
        Replace paragraph text while preserving the paragraph itself.

        Note:
        This intentionally rewrites the paragraph runs. Advanced
        formatting preservation can be handled later if required
        by the final DOCX templates.
        """

        if paragraph.runs:
            paragraph.runs[0].text = text

            for run in paragraph.runs[1:]:
                run.text = ""
        else:
            paragraph.add_run(text)

    # =================================================================
    # CLAUSE PROCESSING
    # =================================================================

    
    @staticmethod
    def _replace_clause_markers(
        doc: Document,
        clauses: Iterable[ApprovedClause],
        requirement: TemplateClauseRequirement,
        sections: List[AssembledSection],
    ) -> set[str]:
        """
        Replace approved M5 clause markers in the M1 template.

        Placement comes only from the M5
        TemplateClauseRequirement / ApprovedClause contract.

        Assembly fails closed if a selected approved clause does
        not have a valid placement marker or if that marker is not
        present in the M1 document template.
        """

        used_markers: set[str] = set()

        for index, clause in enumerate(clauses):

            marker = DocumentAssembler._resolve_marker(
                clause,
                requirement,
            )

            clause_text = DocumentAssembler._get_clause_text(
                clause
            )

            if not clause_text:
                raise ValidationError(
                    "Approved clause has no usable legal text: "
                    + clause.clause_id
                )

            replaced_any = False

            # Normal paragraphs
            for paragraph in doc.paragraphs:

                if marker not in paragraph.text:
                    continue

                new_text = paragraph.text.replace(
                    marker,
                    clause_text,
                )

                DocumentAssembler._replace_paragraph_text(
                    paragraph,
                    new_text,
                )

                replaced_any = True

            # Table paragraphs
            for table in doc.tables:
                for row in table.rows:
                    for cell in row.cells:
                        for paragraph in cell.paragraphs:

                            if marker not in paragraph.text:
                                continue

                            new_text = paragraph.text.replace(
                                marker,
                                clause_text,
                            )

                            DocumentAssembler._replace_paragraph_text(
                                paragraph,
                                new_text,
                            )

                            replaced_any = True

            if not replaced_any:
                raise ValidationError(
                    f"Approved placement marker "
                    f"{marker} for clause "
                    f"{clause.clause_id} "
                    f"was not found in M1 template "
                    f"{requirement.template_id}"
                )

            used_markers.add(marker)

            sections.append(
                AssembledSection(
                    section_id=(
                        f"clause-{clause.clause_id}"
                    ),
                    title=clause.type.value,
                    text=clause_text,
                    order=100000 + index,
                    source_type="approved_clause",
                    source_id=clause.clause_id,
                    clause_id=clause.clause_id,
                    clause_version=clause.version,
                )
            )

        return used_markers
    @staticmethod
    def _resolve_marker(
        clause: ApprovedClause,
        requirement: TemplateClauseRequirement,
    ) -> str:

        insertion_key = (
            clause.metadata.insertion_key
        )

        if not insertion_key:
            raise ValidationError(
                "Missing insertion_key for approved clause: "
                + clause.clause_id
            )

        marker = (
            requirement.section_placeholders.get(
                insertion_key
            )
        )

        if marker:
            return marker

        if (
            insertion_key
            in requirement.section_placeholders.values()
        ):
            return insertion_key

        raise ValidationError(
            f"No approved placement marker for clause "
            f"{clause.clause_id}: "
            f"{insertion_key}"
        )
    @staticmethod
    def _get_clause_text(
        clause: ApprovedClause,
    ) -> str:
        """
        Select the approved clause text.

        Current default is English because the current M1 schema
        does not yet carry a final output-language contract for
        clause assembly.

        Arabic fallback is used only when English text is absent.
        """

        if clause.text_en and clause.text_en.strip():
            return clause.text_en.strip()

        if clause.text_ar and clause.text_ar.strip():
            return clause.text_ar.strip()

        return ""

    # =================================================================
    # DOCUMENT TEXT EXTRACTION
    # =================================================================

    @staticmethod
    def _extract_document_text(
        doc: Document,
    ) -> str:

        final_parts: List[str] = []

        # Normal document paragraphs
        for paragraph in doc.paragraphs:
            text = paragraph.text.strip()

            if text:
                final_parts.append(text)

        # Table content
        for table in doc.tables:
            for row in table.rows:
                for cell in row.cells:
                    for paragraph in cell.paragraphs:
                        text = paragraph.text.strip()

                        if text:
                            final_parts.append(text)

        return "\n".join(final_parts)
    @staticmethod
    def _sort_clauses(
        clauses: list[ApprovedClause],
        requirement: TemplateClauseRequirement,
    ) -> list[ApprovedClause]:

        placement_order = {
            key: index
            for index, key in enumerate(
                requirement.section_placeholders.keys()
            )
        }

        marker_order = {
            marker: index
            for index, marker in enumerate(
                requirement.section_placeholders.values()
            )
        }

        def sort_key(
            clause: ApprovedClause,
        ) -> tuple[int, str]:

            insertion_key = (
                clause.metadata.insertion_key
                or ""
            )

            index = placement_order.get(
                insertion_key,
                marker_order.get(
                    insertion_key,
                    10**9,
                ),
            )

            return (
                index,
                clause.clause_id,
            )

        return sorted(
            clauses,
            key=sort_key,
        )