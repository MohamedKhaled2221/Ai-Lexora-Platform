def looks_visually_ordered(text: str, min_words: int = 4) -> tuple[bool, str]:
    """Heuristically decide whether an Arabic line is stored in *visual* order.

    Returns ``(is_visual, evidence)``.

    The test rests on Arabic orthography rather than on semantics, so it needs
    no dictionary:

      * Arabic letters have contextual forms. In logical order, a word's
        *final* form letters (ـة, ـه, ـي at word end) sit at the end of the
        token. When a line has been reversed character-by-character -- the
        classic broken-extraction case -- those land at the *start* of tokens
        instead.
      * Reversal also strands non-joining letters (ا د ذ ر ز و) in positions
        they cannot occupy.

    Two independent signals must agree before we call a line visual, because a
    false positive here reverses correct text -- strictly worse than leaving a
    genuinely reversed line alone (which at least stays flagged).
    """
    words = [w for w in re.findall(r"\S+", text) if _ARABIC_WORD.search(w)]
    if len(words) < min_words:
        return False, "too few Arabic words to judge"

    # Signal 1: taa marbuta / final-heh at the *start* of tokens.
    final_only = "ةى"
    starts = sum(1 for w in words if w and w[0] in final_only)
    ends = sum(1 for w in words if w and w[-1] in final_only)
    sig1 = starts > ends and starts >= max(2, len(words) * 0.15)

    # Signal 2: the definite article "ال" is extremely frequent in legal Arabic
    # and word-initial. Reversed text shows "لا" word-finally instead.
    al_initial = sum(1 for w in words if w.startswith("ال"))
    la_final = sum(1 for w in words if w.endswith("لا"))
    sig2 = la_final > al_initial and la_final >= 2

    if sig1 and sig2:
        return True, (
            f"final-form letters open {starts}/{len(words)} tokens (vs {ends} closing); "
            f"'لا' ends {la_final} tokens vs 'ال' opening {al_initial}"
        )
    if sig1 or sig2:
        return False, "one reversal signal present but not both; left as-is and flagged"
    return False, "no reversal signals"


def repair_visual_order(text: str) -> tuple[str, bool, str]:
    """Return ``(text, was_repaired, evidence)``.

    Repair is attempted only when :func:`looks_visually_ordered` is confident.
    ``python-bidi``'s ``get_display`` is applied, which maps visual order back
    to logical order for a line that is uniformly RTL.
    """
    is_visual, evidence = looks_visually_ordered(text)
    if not is_visual:
        return text, False, evidence
    try:
        from bidi.algorithm import get_display

        repaired = get_display(text, base_dir="R")
    except Exception as exc:  # noqa: BLE001
        logger.warning("bidi repair failed: %s", exc)
        return text, False, f"bidi repair raised {exc}"

    # Only accept the repair if it actually removed the reversal signals.
    still_visual, _ = looks_visually_ordered(repaired)
    if still_visual:
        return text, False, "bidi pass did not resolve reversal signals; left as-is"
    return repaired, True, evidence


# ---------------------------------------------------------------------------
# Mirrored-neutrals detection (the common Arabic-DTP / OCR artifact)
# ---------------------------------------------------------------------------

# Bracket pairs that mirror under a direction flip.
_MIRROR_PAIRS = {")": "(", "(": ")", "]": "[", "[": "]", "}": "{", "{": "}",
                 "<": ">", ">": "<"}
_OPENERS = "([{"
_CLOSERS = ")]}"


def detect_mirrored_neutrals(text: str) -> tuple[bool, list[str]]:
    """Detect the *partial* visual-order artifact, where words are fine but
    neutral characters are not.

    This is the failure mode that actually dominates in practice, and it is
    distinct from wholesale character reversal:

      * Arabic words keep correct internal letter order, because the renderer
        (or the extractor) re-reversed each RTL run.
      * Digits, brackets and sentence punctuation -- which the Unicode Bidi
        Algorithm treats as *neutral* -- stay where the visual pass left them.

    The observable symptoms, any of which is strong evidence:

      ``)text(``    a closing bracket opening a span and an opener closing it
      ``.النص``     a sentence-final full stop leading the line
      ``٦٢٠٢``      a 4-digit year with its digits reversed (2026 -> 6202)

    Detecting this matters because the obvious repair -- reversing the string --
    is exactly wrong here: it would destroy the *correct* word order. So this is
    reported separately from :func:`looks_visually_ordered`, and only the
    provably safe part is repaired (see :func:`unmirror_brackets`).

    Returns ``(detected, evidence)``.
    """
    evidence: list[str] = []
    if not any(is_arabic_char(c) for c in text):
        return False, evidence

    # 1. Mirrored bracket spans: a closer appearing before its matching opener.
    mirrored = len(re.findall(r"\)[^()]{1,80}\(", text)) + len(re.findall(r"\][^\[\]]{1,80}\[", text))
    normal = len(re.findall(r"\([^()]{1,80}\)", text)) + len(re.findall(r"\[[^\[\]]{1,80}\]", text))
    # A mirrored span in Arabic text is abnormal in itself; requiring it to
    # *outnumber* correct spans misses partially-mirrored pages, which are
    # common when a document mixes pre-shaped and normally-typed runs.
    if mirrored and mirrored >= normal:
        evidence.append(f"{mirrored} mirrored bracket span(s) ')...(' vs {normal} normal")

    # 2. Sentence-final punctuation leading a line.
    leading_stop = sum(
        1 for line in text.splitlines()
        if line.strip() and line.strip()[0] in ".!؟؛"
    )
    if leading_stop:
        evidence.append(f"{leading_stop} line(s) begin with sentence-final punctuation")

    # 3. Reversed 4-digit years. Legal documents are dense with dates, and a
    #    year outside a plausible range whose reverse is inside it is a strong
    #    tell that the digit run was laid out visually.
    reversed_years = 0
    for m in re.finditer(r"(?<!\d)([0-9٠-٩]{4})(?!\d)", text):
        digits = "".join(_WESTERN.get(c, c) for c in m.group(1))
        if not digits.isdigit():
            continue
        value, flipped = int(digits), int(digits[::-1])
        if not (1800 <= value <= 2100) and 1900 <= flipped <= 2100:
            reversed_years += 1
    if reversed_years:
        evidence.append(f"{reversed_years} implausible 4-digit number(s) that are "
                        f"plausible years when reversed")

    return len(evidence) >= 2, evidence


_WESTERN = {c: str(i) for i, c in enumerate("٠١٢٣٤٥٦٧٨٩")}


def unmirror_brackets(text: str) -> tuple[str, int]:
    """Flip mirrored bracket pairs back. Returns ``(text, n_fixed)``.

    Deliberately the *only* automatic repair applied to mirrored-neutral text.
    It is safe because it is purely structural: a span delimited by ``)`` then
    ``(`` has exactly one correct reading, whichever direction the line was
    laid out in. Digits are left strictly alone -- ``٢١`` could be 12 or 21 and
    nothing in the extracted text distinguishes them, so guessing would
    silently corrupt article numbers and amounts. Those are flagged instead.
    """
    n = 0

    def flip(m: re.Match) -> str:
        nonlocal n
        n += 1
        return _MIRROR_PAIRS[m.group(1)] + m.group(2) + _MIRROR_PAIRS[m.group(3)]

    text = re.sub(r"(\))([^()]{1,80})(\()", flip, text)
    text = re.sub(r"(\])([^\[\]]{1,80})(\[)", flip, text)
    return text, n


def to_display_form(text: str) -> str:
    """Reshape + bidi into presentation/visual form, for **rendering only**.

    Never store the result in ``DocumentChunk.text``. See the module docstring.
    """
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display

        return get_display(arabic_reshaper.reshape(text))
    except Exception as exc:  # noqa: BLE001
        logger.warning("display shaping failed: %s", exc)
        return text


