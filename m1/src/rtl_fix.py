def document_visual_order(doc: ExtractedDocument, cfg: RTLConfig):
    """Document-level visual-order verdict for text that has no glyph geometry.

    The PDF text path settles this in the extractor, where glyph positions make
    the answer exact (see
    :func:`src.extract_pymupdf_docling._resolve_reading_order`). OCR, DOCX and
    plaintext have no such evidence: all that exists is the string, so the
    candidate reading is the one :func:`~src.visual_order.visual_to_logical`
    derives from it, and the decision is the same two-criteria reversal test.

    Taken once for the document rather than per block, for the same reason as
    on the PDF path: visual layout is a property of the producer, and a short
    block cannot carry enough evidence to convict itself.

    Returns a :class:`~src.visual_order.ReorderVerdict`, or ``None`` when there
    is nothing to judge.
    """
    from .visual_order import choose_reading, visual_to_logical

    if not cfg.enabled or not cfg.repair_visual_order:
        return None

    blocks = [
        b for b in doc.all_blocks()
        if not b.is_empty() and not b.reading_order_repaired and not b.geometric_text
        and detect_language(b.text) in (Language.AR, Language.AR_EN)
    ]
    if not blocks:
        return None

    stream = "\n".join(strip_presentation_forms(b.text) for b in blocks)
    candidate = "\n".join(
        visual_to_logical(b.text) if any(is_arabic_char(c) for c in b.text)
        else b.text
        for b in blocks
    )
    verdict = choose_reading(stream, candidate)
    doc.log_engine(None, "reading_order", source="string-only", **verdict.as_dict())
    return verdict


def _apply_visual_order(block: TextBlock, text: str, verdict) -> tuple[str, bool]:
    """Apply an accepted document-level verdict to one block's text."""
    from .visual_order import visual_to_logical

    if verdict is None or not verdict.repaired:
        return text, False
    if not any(is_arabic_char(c) for c in text):
        return text, False
    repaired = visual_to_logical(text)
    return (repaired, True) if repaired != text else (text, False)


def fix_block(block: TextBlock, cfg: RTLConfig, doc_mirrored: bool = False,
              order_verdict=None) -> TextBlock:
    """Apply RTL handling to one block, in place.

    Order of operations:
      1. record ``raw_text``
      2. analyze and attach flags (before any change, so flags describe the
         source, not our output)
      3. fold presentation forms, if any
      4. repair mirrored neutrals, or repair visual order -- never both
      5. optionally produce ``display_text``

    ``doc_mirrored`` is the document-level verdict from
    :func:`document_is_mirrored`. Mirrored layout is a property of the software
    that produced the file, not of individual paragraphs, so once it is
    established for the document every Arabic block is treated as affected. A
    short heading block on its own rarely carries enough evidence to be
    convicted, which is exactly where the damage is most visible.
    """
    if not cfg.enabled or block.is_empty():
        return block

    if block.raw_text is None:
        block.raw_text = block.text

    text = block.text
    block.rtl_flags.extend(analyze_direction(text, cfg, page=block.page))

    lang = detect_language(text)
    if lang in (Language.AR, Language.AR_EN):
        # A document-level visual-order verdict, when one was reached, is
        # applied *before* presentation forms are folded: the lam-alef ligature
        # is one glyph and therefore one position in a visual string, and
        # decomposing it first makes the reversal split it the wrong way round
        # ("الإيجار" -> "اإليجار"). See src.visual_order.visual_to_logical.
        text, reordered = _apply_visual_order(block, text, order_verdict)
        if reordered:
            block.reading_order_repaired = True
            block.rtl_flags.append(
                RTLFlag(
                    kind="visual_order_repaired", page=block.page, severity="warn",
                    detail="text arrived in VISUAL reading order and was reordered "
                           "to logical order. " + order_verdict.reason
                           + " Digit *order* was not touched.",
                    sample=" ".join(text.split())[:120],
                )
            )

        folded = strip_presentation_forms(text)
        if folded != text:
            text = folded

        if block.reading_order_repaired:
            # Already settled by geometry (PDF) or by the document verdict
            # above. The mirrored-neutral and full-reversal heuristics below
            # answer the same question with weaker evidence, and running them
            # on top of a completed repair would reverse it back.
            block.text = text
            if cfg.emit_display_form or cfg.force_display_in_text:
                block.display_text = to_display_form(text)
                if cfg.force_display_in_text:
                    block.text = block.display_text
            return block

        # Partial visual order: words correct, neutrals mirrored. Checked
        # before full-reversal repair, because the two are mutually exclusive
        # and reversing this case would destroy correct word order.
        mirrored, mirror_evidence = detect_mirrored_neutrals(text)
        if doc_mirrored and not mirrored:
            mirrored = True
            mirror_evidence = mirror_evidence or ["document-level mirrored layout detected"]
        if mirrored:
            block.rtl_flags.append(
                RTLFlag(
                    kind="neutral_order_mirrored", page=block.page, severity="warn",
                    detail="text was laid out visually: Arabic words are in correct "
                           "order but neutral characters (brackets, digits, sentence "
                           "punctuation) are mirrored. Evidence: "
                           + "; ".join(mirror_evidence)
                           + ". Brackets are repaired; DIGITS ARE NOT -- article "
                             "numbers, dates and amounts on this page may be "
                             "digit-reversed and need manual verification.",
                    sample=" ".join(text.split())[:120],
                )
            )
            if cfg.repair_visual_order:
                text, n_fixed = unmirror_brackets(text)
                if n_fixed:
                    block.rtl_flags.append(
                        RTLFlag(
                            kind="brackets_unmirrored", page=block.page, severity="info",
                            detail=f"{n_fixed} mirrored bracket pair(s) flipped back "
                                   f"(structural, unambiguous repair)",
                            sample=" ".join(text.split())[:120],
                        )
                    )
            if any("digit" in e or "year" in e for e in mirror_evidence):
                block.rtl_flags.append(
                    RTLFlag(
                        kind="digit_order_suspect", page=block.page, severity="warn",
                        detail="numeric runs on this block appear digit-reversed. "
                               "NOT auto-corrected: '٢١' is indistinguishable from "
                               "'١٢' in extracted text, so a guess would silently "
                               "corrupt article numbers and amounts.",
                        sample=" ".join(text.split())[:120],
                    )
                )

        if cfg.repair_visual_order and not mirrored:
            repaired, did, evidence = repair_visual_order(text)
            if did:
                text = repaired
                block.rtl_flags.append(
                    RTLFlag(
                        kind="visual_order_repaired", page=block.page, severity="warn",
                        detail=f"text was stored in visual order and was reversed to logical "
                               f"order. Evidence: {evidence}. Verify against the source page.",
                        sample=" ".join(text.split())[:120],
                    )
                )
            elif "one reversal signal" in evidence:
                block.rtl_flags.append(
                    RTLFlag(
                        kind="visual_order_suspected", page=block.page, severity="warn",
                        detail=f"possible visual-order storage but evidence was not conclusive; "
                               f"text left unchanged. {evidence}",
                        sample=" ".join(text.split())[:120],
                    )
                )

    block.text = text
    if cfg.emit_display_form or cfg.force_display_in_text:
        block.display_text = to_display_form(text)
        if cfg.force_display_in_text:
            block.text = block.display_text
    return block


def apply_rtl_fix(doc: ExtractedDocument, cfg: RTLConfig) -> ExtractedDocument:
    """Run RTL handling across every block, and summarize flags per page.

    Runs after extraction (both paths) and before chunking, exactly where the
    spec places it: both OCR output and PyMuPDF/Docling output can carry
    reading-order damage, so a single pass over the shared IR covers both.
    """
    if not cfg.enabled:
        return doc

    # Reading order first, and once for the document: everything below reasons
    # about mirrored neutrals and orthography, and both are meaningless until
    # the text is in the order it will actually be consumed in.
    order_verdict = document_visual_order(doc, cfg)
    if order_verdict is not None and order_verdict.repaired:
        doc.warnings.append(
            "text arrived in VISUAL reading order and was reordered to logical "
            "order (no glyph geometry available for this source, so the decision "
            f"was made from the text alone). {order_verdict.reason} Reordered "
            "blocks carry a visual_order_repaired flag."
        )

    doc_mirrored, doc_evidence = document_is_mirrored(doc)
    if doc_mirrored:
        doc.warnings.append(
            "document appears to have been laid out VISUALLY (Arabic words correct, "
            "neutral characters mirrored). Evidence: " + "; ".join(doc_evidence)
            + ". Brackets repaired; digit order NOT corrected -- verify article "
              "numbers, dates and amounts against the source."
        )
        doc.log_engine(None, "rtl_fix", mirrored_layout=True, evidence=doc_evidence)

    total_flags = 0
    for page in doc.pages:
        for block in page.blocks:
            fix_block(block, cfg, doc_mirrored=doc_mirrored, order_verdict=order_verdict)
            total_flags += len(block.rtl_flags)
        # Table cells get the same treatment.
        for table in page.tables:
            table.rows = [
                [strip_presentation_forms(cell) if cell else cell for cell in row]
                for row in table.rows
            ]

    if total_flags:
        doc.warnings.append(
            f"{total_flags} RTL/reading-order flags raised across "
            f"{doc.n_pages} pages; see chunk metadata.rtl_flags for detail"
        )
        doc.log_engine(None, "rtl_fix", flags=total_flags)
    return doc


def document_is_mirrored(doc: ExtractedDocument, sample_chars: int = 20000) -> tuple[bool, list[str]]:
    """Decide whether the whole document was laid out visually.

    Aggregating across the document is what makes this reliable. Mirrored
    layout comes from the producing software (Arabic DTP that shapes text
    before writing it, or an OCR engine emitting visual order), so it is
    all-or-nothing per file. Individual short blocks -- headings especially --
    do not carry enough evidence on their own, yet they are where the mirroring
    is most visible to a reader.

    A sample of the document's Arabic text is used rather than all of it, since
    the signals saturate quickly and a 90-page statute would otherwise be
    scanned twice for nothing.
    """
    parts, total = [], 0
    for block in doc.all_blocks():
        if block.is_empty():
            continue
        parts.append(block.text)
        total += len(block.text)
        if total >= sample_chars:
            break
    if not parts:
        return False, []
    return detect_mirrored_neutrals(strip_presentation_forms("\n".join(parts)))


def collect_flags(doc: ExtractedDocument) -> list[RTLFlag]:
    """All RTL flags in the document, for reporting."""
    out: list[RTLFlag] = []
    for block in doc.all_blocks():
        out.extend(block.rtl_flags)
    return out
