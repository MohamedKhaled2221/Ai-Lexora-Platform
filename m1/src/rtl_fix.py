# Ambiguity analysis (flag, do not fix)
# ---------------------------------------------------------------------------


def _direction_runs(text: str) -> list[tuple[str, str]]:
    """Split text into maximal runs of one direction.

    Digits and punctuation are *neutral*: they attach to whichever run they sit
    inside rather than opening a new one. This matters because Arabic legal text
    is dense with numbers, and counting every number as a direction switch would
    flag essentially every page.
    """
    runs: list[tuple[str, str]] = []
    current_dir, buf = None, []
    for ch in text:
        if is_arabic_char(ch):
            d = "R"
        elif is_latin_char(ch):
            d = "L"
        else:
            d = None  # neutral
        if d is None:
            buf.append(ch)
            continue
        if current_dir is None:
            current_dir = d
        elif d != current_dir:
            runs.append((current_dir, "".join(buf)))
            buf, current_dir = [], d
        buf.append(ch)
    if buf and current_dir:
        runs.append((current_dir, "".join(buf)))
    return runs


def analyze_direction(text: str, cfg: RTLConfig, page: int | None = None) -> list[RTLFlag]:
    """Produce reading-order flags for one block. **Never modifies the text.**

    Flags raised:

    ``presentation_forms_found``
        Source stored glyphs, not characters. Normalization will fold them, but
        the page is worth eyeballing because glyph-level storage often comes
        with other damage.
    ``mixed_direction``
        Arabic and Latin both materially present -- the ordering of the
        embedded run relative to its host is not recoverable from plain text.
    ``high_switch_count``
        More direction switches than ``max_direction_switches_before_flag``.
        Typical of bilingual clause tables and defined-term lists; these are the
        pages most likely to be wrong.
    ``numeral_direction_ambiguous``
        A numeral sits at a direction boundary. In an RTL paragraph "المادة 12"
        and "12 المادة" are visually identical for a lone number, so article
        and clause numbers can attach to the wrong side.
    """
    flags: list[RTLFlag] = []
    if not cfg.flag_mixed_direction or not text.strip():
        return flags

    sample = " ".join(text.split())[:120]

    if has_presentation_forms(text):
        flags.append(
            RTLFlag(
                kind="presentation_forms_found", page=page, severity="info",
                detail="text contains Arabic presentation forms (glyph codepoints); "
                       "normalization will fold these to base letters",
                sample=sample,
            )
        )

    controls = {name for ch, name in _BIDI_CONTROLS.items() if ch in text}
    profile = script_profile(text)
    n_latin_words = len(_LATIN_WORD.findall(text))
    n_arabic_words = len(_ARABIC_WORD.findall(text))

    if profile["arabic"] and profile["latin"] >= cfg.mixed_direction_min_latin_chars:
        if n_arabic_words and n_latin_words:
            flags.append(
                RTLFlag(
                    kind="mixed_direction", page=page, severity="warn",
                    detail=(
                        f"{n_arabic_words} Arabic and {n_latin_words} Latin words share this "
                        f"block ({profile['arabic']} vs {profile['latin']} chars)"
                        + (f"; bidi controls present: {sorted(controls)}" if controls else "")
                        + ". Reading order of the embedded run is not recoverable from "
                          "plain text -- not auto-corrected, review against the source."
                    ),
                    sample=sample,
                )
            )

    runs = _direction_runs(text)
    switches = sum(1 for a, b in zip(runs, runs[1:]) if a[0] != b[0])
    if switches > cfg.max_direction_switches_before_flag:
        flags.append(
            RTLFlag(
                kind="high_switch_count", page=page, severity="warn",
                detail=f"{switches} bidirectional direction switches in one block "
                       f"(threshold {cfg.max_direction_switches_before_flag})",
                sample=sample,
            )
        )

    # Numerals adjacent to a direction boundary.
    if profile["arabic"] and profile["digit"]:
        for m in re.finditer(r"\d+|[٠-٩]+", text):
            before = text[max(0, m.start() - 2): m.start()]
            after = text[m.end(): m.end() + 2]
            has_ar = any(is_arabic_char(c) for c in before + after)
            has_lat = any(is_latin_char(c) for c in before + after)
            if has_ar and has_lat:
                flags.append(
                    RTLFlag(
                        kind="numeral_direction_ambiguous", page=page, severity="warn",
                        detail=f"numeral '{m.group()}' sits between Arabic and Latin text; "
                               "its side of attachment is ambiguous (affects article/clause "
                               "numbering)",
                        sample=" ".join(text[max(0, m.start() - 30): m.end() + 30].split()),
                    )
                )
                break  # one flag per block is enough to trigger review
    return flags


