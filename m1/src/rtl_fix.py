"""RTL reading-order repair and shaping, with explicit ambiguity flagging.

WHAT THIS MODULE IS FOR (please read before changing defaults)
=============================================================

``arabic_reshaper`` and ``python-bidi`` do one thing: convert *logical-order*
Arabic into *visual-order presentation forms* -- the shape you need when you
are painting glyphs onto a surface that has no bidi engine of its own (a PDF
canvas, a plotting library, a dumb terminal).

That is the **opposite** of what a retrieval pipeline wants. Presentation forms
(U+FB50-U+FEFF) are different codepoints from the base letters. Text in visual
order has its words reversed relative to logical order. Feed either to an
embedding model or a tokenizer and retrieval quality collapses, silently.

So this module deliberately splits the two jobs the libraries can do:

**Job 1 -- repair (default ON).** Detect text that arrived *already* in visual
order or *already* full of presentation forms -- a real and common artifact of
OCR and of PDFs generated by older Arabic DTP software -- and put it back into
logical order with base letters. ``python-bidi`` is used here in reverse: its
``get_display`` is an involution on a fully-reversed pure-RTL line, so applying
it to visually-ordered text recovers logical order. This is the fix that
actually matters for M2/M3.

**Job 2 -- display form (default OFF).** Produce the reshaped/bidi'd
presentation string for rendering, and store it in
``metadata.display_text``. It never touches ``DocumentChunk.text`` unless
``RTLConfig.force_display_in_text`` is explicitly set.

**Flagging, not fixing.** Per the spec, mixed Arabic/English/numeral content
whose reading order is genuinely ambiguous is *surfaced*, never silently
rewritten. :func:`analyze_direction` produces :class:`RTLFlag` records that ride
along on the chunk metadata and are aggregated into the evaluation report for
manual review. Nothing in this module rewrites a block it has flagged as
ambiguous -- the flag exists precisely because a machine cannot safely decide.

Why ambiguity is unavoidable: the Unicode Bidi Algorithm resolves a
bidirectional run against a *paragraph direction* that is not stored in
extracted plain text. "المادة 12 (Article 12) تنص" has one correct rendering
under RTL paragraph direction and a different one under LTR. Extraction loses
that context, so any automatic choice is a guess. We flag instead.
"""

from __future__ import annotations

import logging
import re
import unicodedata

from .config import RTLConfig
from .document_chunk_schema import Language, RTLFlag
from .structure_preservation import (
    ExtractedDocument,
    TextBlock,
    detect_language,
    is_arabic_char,
    is_latin_char,
    script_profile,
)

logger = logging.getLogger(__name__)

# Arabic Presentation Forms A and B. Their presence in extracted text is the
# single strongest signal that the source stored glyphs rather than characters.
_PRESENTATION_A = (0xFB50, 0xFDFF)
_PRESENTATION_B = (0xFE70, 0xFEFF)

# Explicit bidi control characters. Their presence means someone already tried
# to pin down direction -- worth noticing before we make our own decision.
_BIDI_CONTROLS = {
    "‎": "LRM", "‏": "RLM",
    "‪": "LRE", "‫": "RLE", "‬": "PDF",
    "‭": "LRO", "‮": "RLO",
    "⁦": "LRI", "⁧": "RLI", "⁨": "FSI", "⁩": "PDI",
}

_ARABIC_WORD = re.compile(r"[؀-ۿݐ-ݿࢠ-ࣿ]{2,}")
_LATIN_WORD = re.compile(r"[A-Za-z]{2,}")


def has_presentation_forms(text: str) -> bool:
    return any(
        _PRESENTATION_A[0] <= ord(c) <= _PRESENTATION_A[1]
        or _PRESENTATION_B[0] <= ord(c) <= _PRESENTATION_B[1]
        for c in text
    )


def strip_presentation_forms(text: str) -> str:
    """Map presentation forms back to base letters via NFKC compatibility
    decomposition, then drop the leftover combining marks NFKC introduces.

    NFKC is the right tool: it is exactly the mapping from a contextual glyph
    (isolated/initial/medial/final) to its canonical letter. Lam-alef ligatures
    decompose to two characters, which is also what we want.
    """
    if not has_presentation_forms(text):
        return text
    return unicodedata.normalize("NFKC", text)


